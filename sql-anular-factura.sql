-- Anular una factura de ARCA con Nota de Crédito y devolver el pedido a "Pedido" para editarlo y refacturarlo.
-- Correr UNA VEZ en Supabase -> SQL Editor -> Run. Es seguro de volver a correr.
--
-- Cómo funciona (la nota de crédito la emite la API del servidor; esta parte guarda el historial):
--  * La factura anulada y su nota de crédito quedan guardadas en facturas_anuladas (números, CAE,
--    fechas, cliente, total, productos tal como se facturaron, motivo y quién). No se borran nunca.
--  * El pedido queda sin factura ni nota de crédito: vuelve a "Pedido", editable, y se puede
--    volver a facturar con una Factura C nueva (número nuevo).
--  * No se anula si el pedido figura cobrado: primero hay que anular el cobro.
--  * Si el pedido también tiene un remito, el remito no se toca (se anula aparte).

-- Monto con el que se emitió la factura (la nota de crédito siempre es por ese mismo monto).
alter table pedidos_distribuidora add column if not exists factura_total numeric;

create table if not exists facturas_anuladas (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null,
  comercio text,
  factura_tipo int,
  factura_pto_vta int,
  factura_nro bigint,
  factura_cae text,
  factura_cae_vencimiento date,
  facturado_en timestamptz,
  factura_cuit_cliente text,
  factura_cliente_razon_social text,
  factura_cliente_domicilio text,
  factura_cliente_condicion_iva text,
  factura_total numeric,
  productos jsonb,
  nc_tipo int,
  nc_pto_vta int,
  nc_nro bigint,
  nc_cae text,
  nc_cae_vencimiento date,
  nc_facturada_en timestamptz,
  motivo text not null,
  anulado_por text,
  anulado_en timestamptz not null default now()
);
create index if not exists facturas_anuladas_pedido_idx on facturas_anuladas (pedido_id);

alter table facturas_anuladas enable row level security;
-- Solo lectura para usuarios logueados. Los registros los crea únicamente la función de abajo.
drop policy if exists "Lectura facturas anuladas" on facturas_anuladas;
create policy "Lectura facturas anuladas" on facturas_anuladas for select to authenticated using (true);

-- Archiva la factura anulada (que ya debe tener su nota de crédito emitida) y devuelve el pedido a "Pedido".
create or replace function archivar_factura_anulada(p_pedido bigint, p_motivo text, p_usuario text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v pedidos_distribuidora%rowtype;
begin
  select * into v from pedidos_distribuidora where id = p_pedido for update;
  if not found then raise exception 'El pedido no existe'; end if;
  if v.factura_cae is null then raise exception 'El pedido no tiene una factura para anular'; end if;
  if v.nc_cae is null then raise exception 'Primero hay que emitir la nota de crédito en ARCA'; end if;
  if v.cobro in ('Efectivo', 'Transferencia', 'Mercado Pago') or (v.estado_pago = 'Mercado Pago' and coalesce(v.pagado, false)) then
    raise exception 'El pedido figura como cobrado: primero anulá el cobro';
  end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Falta el motivo de la anulación'; end if;

  insert into facturas_anuladas
    (pedido_id, comercio, factura_tipo, factura_pto_vta, factura_nro, factura_cae, factura_cae_vencimiento, facturado_en,
     factura_cuit_cliente, factura_cliente_razon_social, factura_cliente_domicilio, factura_cliente_condicion_iva,
     factura_total, productos, nc_tipo, nc_pto_vta, nc_nro, nc_cae, nc_cae_vencimiento, nc_facturada_en, motivo, anulado_por)
  values
    (v.id, v.comercio, v.factura_tipo, v.factura_pto_vta, v.factura_nro, v.factura_cae, v.factura_cae_vencimiento, v.facturado_en,
     v.factura_cuit_cliente, v.factura_cliente_razon_social, v.factura_cliente_domicilio, v.factura_cliente_condicion_iva,
     coalesce(v.factura_total, v.total), v.productos, v.nc_tipo, v.nc_pto_vta, v.nc_nro, v.nc_cae, v.nc_cae_vencimiento, v.nc_facturada_en,
     trim(p_motivo), p_usuario);

  update pedidos_distribuidora
     set factura_cae = null, factura_cae_vencimiento = null, factura_tipo = null, factura_pto_vta = null,
         factura_nro = null, factura_cuit_cliente = null, factura_cliente_razon_social = null,
         factura_cliente_domicilio = null, factura_cliente_condicion_iva = null, facturado_en = null,
         factura_total = null,
         nc_cae = null, nc_cae_vencimiento = null, nc_tipo = null, nc_pto_vta = null, nc_nro = null,
         nc_motivo = null, nc_facturada_en = null
   where id = p_pedido;

  -- Sin remito, el pedido vuelve a Pendiente (editable). Con remito, se mantiene su estado de entrega.
  if v.remito_nro is null then
    update pedidos_distribuidora
       set estado = 'Pendiente', estado_entrega = 'Pendiente', fecha_entrega = null
     where id = p_pedido;
  end if;
end;
$$;

-- Solo la API del servidor (que emite la nota de crédito antes) puede llamarla.
revoke all on function archivar_factura_anulada(bigint, text, text) from public, anon, authenticated;
grant execute on function archivar_factura_anulada(bigint, text, text) to service_role;
