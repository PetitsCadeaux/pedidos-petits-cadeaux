-- Anular un remito (no fiscal) y devolver el pedido a "Pedido" para poder editarlo.
-- Correr UNA VEZ en Supabase -> SQL Editor -> Run. Es seguro de volver a correr.
--
-- * El remito anulado queda guardado en remitos_anulados (numero, fecha, motivo, quien,
--   y una copia de los productos tal como salieron). No se borra nunca.
-- * El numero anulado NO se reutiliza: el proximo remito toma un numero nuevo (secuencia).
-- * Si el pedido figura como cobrado, primero hay que anular el cobro (en Facturacion).
-- * Si el pedido tiene factura de ARCA, no se anula por aca (va con nota de credito).

create table if not exists remitos_anulados (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null,
  comercio text,
  remito_pto_vta int,
  remito_nro bigint,
  remito_en timestamptz,
  remito_total numeric,
  productos jsonb,
  motivo text not null,
  anulado_por text,
  anulado_en timestamptz not null default now()
);

create index if not exists remitos_anulados_pedido_idx on remitos_anulados (pedido_id);

alter table remitos_anulados enable row level security;

-- Solo lectura para usuarios logueados. Nadie puede insertar, editar ni borrar a mano:
-- los registros los crea unicamente la funcion anular_remito (queda como historial).
drop policy if exists "Lectura remitos anulados" on remitos_anulados;
create policy "Lectura remitos anulados"
  on remitos_anulados for select
  to authenticated
  using (true);

create or replace function anular_remito(p_pedido bigint, p_motivo text, p_usuario text)
returns table(o_pto_vta int, o_nro bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  v pedidos_distribuidora%rowtype;
begin
  select * into v from pedidos_distribuidora where id = p_pedido for update;
  if not found then
    raise exception 'El pedido no existe';
  end if;
  if v.remito_nro is null then
    raise exception 'El pedido no tiene remito para anular';
  end if;
  if v.factura_cae is not null then
    raise exception 'El pedido tiene una factura emitida: se anula con nota de credito, no desde el remito';
  end if;
  if v.cobro in ('Efectivo', 'Transferencia', 'Mercado Pago') or (v.estado_pago = 'Mercado Pago' and coalesce(v.pagado, false)) then
    raise exception 'El pedido figura como cobrado: primero anula el cobro y despues el remito';
  end if;
  if coalesce(trim(p_motivo), '') = '' then
    raise exception 'Falta el motivo de la anulacion';
  end if;

  insert into remitos_anulados
    (pedido_id, comercio, remito_pto_vta, remito_nro, remito_en, remito_total, productos, motivo, anulado_por)
  values
    (v.id, v.comercio, v.remito_pto_vta, v.remito_nro, v.remito_en, v.remito_total, v.productos, trim(p_motivo), p_usuario);

  -- El pedido vuelve a estado "Pedido": sin remito, sin entrega registrada, editable.
  update pedidos_distribuidora
     set remito_pto_vta = null,
         remito_nro = null,
         remito_en = null,
         remito_total = null,
         estado = 'Pendiente',
         estado_entrega = 'Pendiente',
         fecha_entrega = null
   where id = p_pedido;

  return query select v.remito_pto_vta, v.remito_nro;
end;
$$;

revoke all on function anular_remito(bigint, text, text) from public, anon;
grant execute on function anular_remito(bigint, text, text) to authenticated;
